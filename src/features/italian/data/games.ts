export type GameId =
  | "gn"
  | "gli"
  | "gli-li"
  | "sc"
  | "ch"
  | "cu"
  | "double-consonants"
  | "doppie-scegli"
  | "accents"
  | "h"
  | "mp-mb"
  | "apostrophe"
  | "sillabe";

export type Entry = {
  id: string;
  /** Il testo mostrato nella domanda, con "__" al posto delle lettere da scegliere. */
  pattern: string;
  /** La risposta corretta: lettere (modalità "letters") o parola (modalità "words"). */
  answer: string;
  /**
   * Le alternative sbagliate, sempre diverse dalla risposta (di solito tre).
   * Vuote nel gioco delle sillabe, dove il bambino mette le stanghette da solo.
   */
  options: string[];
  /** La parola o la frase completa mostrata nel feedback e nel riepilogo. */
  solution: string;
  /** Testo pronunciato dal pulsante Ascolta. */
  spoken: string;
  image?: string;
  color?: string;
  number?: number;
  /** Un indizio breve, utile quando non c'è un'illustrazione. */
  hint?: string;
  /** La regola spiegata in una frase semplice. */
  note: string;
};

export type Game = {
  id: GameId;
  title: string;
  focus: string;
  description: string;
  prompt: string;
  label: string;
  intro: string;
  /**
   * letters: il bambino scrive la parola intera; words: scrive la parola che manca;
   * choices: sceglie tra quattro parole; syllables: mette le stanghette tra le sillabe.
   */
  mode: "letters" | "words" | "choices" | "syllables";
  /**
   * Il suono su cui si allena il gioco: nei giochi a lettere sono le risposte
   * possibili, nei giochi a scelta le lettere contenute nella parola giusta.
   * Se presente, ogni round mescola in parti uguali parole con il suono e tranelli.
   */
  targets?: readonly string[];
  entries: Entry[];
};

