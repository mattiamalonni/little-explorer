export type Question = { entry: Entry; options: string[] };
export type Answer = {
  entry: Entry;
  /** La parola intera scritta dal bambino. */
  selected: string;
  /** La parola intera attesa per questa domanda. */
  expected: string;
  correct: boolean;
};

/** La parola che il bambino deve scrivere per intero. */
export function expectedAnswer(game: Game, entry: Entry): string {
  return game.mode === "letters" ? entry.solution : entry.answer;
}

export function normalizeAnswer(value: string): string {
  return value
    .normalize("NFC")
    .trim()
    .toLocaleLowerCase("it")
    .replace(/[’‘]/g, "'")
    .replace(/\s+/g, " ")
    .replace(/^[^\p{L}]+|[^\p{L}]+$/gu, "");
}

export function isAnswerCorrect(
  game: Game,
  entry: Entry,
  value: string,
): boolean {
  const expected = normalizeAnswer(expectedAnswer(game, entry));
  return expected.length > 0 && normalizeAnswer(value) === expected;
}

export type Round = {
  gameId: GameId;
  questions: Question[];
  answers: Answer[];
};

export function shuffle<Value>(
  values: readonly Value[],
  random = Math.random,
): Value[] {
  const result = [...values];
  for (let index = result.length - 1; index > 0; index--) {
    const target = Math.floor(random() * (index + 1));
    [result[index], result[target]] = [result[target], result[index]];
  }
  return result;
}

export function createRound(
  gameId: GameId,
  previous?: Round,
  random = Math.random,
): Round {
  const game = games.find((entry) => entry.id === gameId);
  if (!game) throw new Error("Unknown game");
  const entries = shuffle(game.entries, random).slice(0, 6);
  if (previous?.questions[0].entry.id === entries[0].id) {
    [entries[0], entries[1]] = [entries[1], entries[0]];
  }
  return {
    gameId,
    questions: entries.map((entry) => ({
      entry,
      options: shuffle([entry.answer, ...entry.options], random),
    })),
    answers: [],
  };
}

export function scoreRound(answers: Answer[]) {
  return answers.filter((answer) => answer.correct).length;
}
