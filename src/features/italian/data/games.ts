export function syllableCount(entry: Entry): number {
  return entry.answer.split("-").length;
}

export function syllableKind(count: number): SyllableKind {
  if (count <= 1) return "monosillaba";
  if (count === 2) return "bisillaba";
  if (count === 3) return "trisillaba";
  if (count === 4) return "quadrisillaba";
  return "polisillaba";
}

/**
 * Costruisce la divisione scritta dal bambino: `cuts` sono le posizioni dopo cui
 * mettere la stanghetta (0 = dopo la prima lettera). Esempio: ("CASA", [1]) → "ca-sa".
 */
export function splitWord(word: string, cuts: Iterable<number>): string {
  const letters = Array.from(word.toLocaleLowerCase("it"));
  const after = new Set(cuts);
  return letters.map((letter, index) => (after.has(index) && index < letters.length - 1 ? `${letter}-` : letter)).join("");
}

export function normalizeAnswer(value: string): string {
  return value
    .normalize("NFC")
    .trim()
    .toLocaleLowerCase("it")
    .replace(/[’‘]/g, "'")
    .replace(/\s+/g, " ")
    .replace(/^[^\p{L}]+|[^\p{L}]+$/gu, "");
}

export function isAnswerCorrect(game: Game, entry: Entry, value: string): boolean {
  const expected = normalizeAnswer(expectedAnswer(game, entry));
  return expected.length > 0 && normalizeAnswer(value) === expected;
}

export type Round = {
  id: string;
  gameId: GameId;
  /** Le voci disponibili per questa partita, usate per rigiocare. */
  selection: string[];
  roundLength: number;
  questions: Question[];
  answers: Answer[];
};

export function shuffle<Value>(values: readonly Value[], random = Math.random): Value[] {
  const result = [...values];
  for (let index = result.length - 1; index > 0; index--) {
    const target = Math.floor(random() * (index + 1));
    [result[index], result[target]] = [result[target], result[index]];
  }
  return result;
}

export type RoundOptions = {
  /** Le voci scelte nella schermata pre-gioco. Se assente, si usano tutte. */
  entries?: readonly string[];
  length?: number;
};

/**
 * Sceglie le voci del round. Per i giochi con `targets` metà delle domande
 * (o quante ne permettono le voci scelte) sono tranelli senza quelle lettere,
 * così il bambino non può rispondere sempre allo stesso modo.
 */
/** Vero se la voce contiene il suono del gioco (vedi `Game.targets`). */
export function hasSound(game: Game, entry: Entry): boolean {
  const targets = game.targets ?? [];
  if (game.mode === "choices") {
    const word = entry.answer.toLocaleUpperCase("it");
    return targets.some((target) => word.includes(target));
  }
  return targets.includes(entry.answer);
}

export function pickEntries(game: Game, pool: readonly Entry[], length: number, random = Math.random): Entry[] {
  if (!game.targets) return shuffle(pool, random).slice(0, length);
  const sound = shuffle(
    pool.filter((entry) => hasSound(game, entry)),
    random,
  );
  const traps = shuffle(
    pool.filter((entry) => !hasSound(game, entry)),
    random,
  );
  const trapCount = Math.min(traps.length, Math.max(length - sound.length, Math.floor(length / 2)));
  return shuffle([...sound.slice(0, length - trapCount), ...traps.slice(0, trapCount)], random);
}

export function createRound(gameId: GameId, options: RoundOptions = {}, previous?: Round, random = Math.random): Round {
  const game = games.find((entry) => entry.id === gameId);
  if (!game) throw new Error("Unknown game");
  const chosen = options.entries ? new Set(options.entries) : null;
  const available = chosen ? game.entries.filter((entry) => chosen.has(entry.id)) : game.entries;
  const pool = available.length > 0 ? available : game.entries;
  const length = Math.min(Math.max(Math.floor(options.length ?? 6), 1), pool.length);
  const entries = pickEntries(game, pool, length, random);
  if (entries.length > 1 && previous?.questions[0]?.entry.id === entries[0].id) {
    [entries[0], entries[1]] = [entries[1], entries[0]];
  }
  return {
    id: `round-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
    gameId,
    selection: pool.map((entry) => entry.id),
    roundLength: length,
    questions: entries.map((entry) => ({
      entry,
      options: shuffle([entry.answer, ...entry.options], random),
    })),
    answers: [],
  };
}

export function scoreRound(answers: Answer[]) {
  return answers.filter((answer) => answer.correct).length;
}
